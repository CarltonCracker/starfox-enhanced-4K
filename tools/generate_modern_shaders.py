"""Offline SDL_GPU scene shaders for MODERN (SPIR-V + DXIL); no runtime compiler."""
import argparse
import pathlib
import subprocess
import tempfile
from portable_shader_source import source_digest

parser = argparse.ArgumentParser()
parser.add_argument('--dxc')
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
root = pathlib.Path(__file__).resolve().parents[1]
source = root / 'src/modern/shaders/scene_sdl.hlsl'
output = root / 'src/modern/shaders/generated/scene_sdl.hpp'
stamp = '// Source SHA-256: ' + source_digest(source)
if args.check:
    if not output.exists() or stamp not in output.read_text().splitlines()[:3]:
        raise SystemExit('MODERN scene shaders stale; run tools/generate_modern_shaders.py --dxc DXC.')
    raise SystemExit(0)
if not args.dxc:
    parser.error('--dxc required for generation')
stages = [('vertex', 'vs_6_0', 'sdl_vertex_textured_main', []),
          ('fragment', 'ps_6_0', 'fragment_textured_main', ['-D', 'STARFOX_SDL_FRAGMENT'])]
text = ('// Generated by tools/generate_modern_shaders.py; do not edit.\n' + stamp + '\n#pragma once\n'
        'namespace starfox::modern::shader {\n')
with tempfile.TemporaryDirectory() as temporary:
    for name, profile, entry, defines in stages:
        for target, flags in (('spirv', ['-spirv', '-fspv-target-env=vulkan1.0']), ('dxil', [])):
            binary = pathlib.Path(temporary) / f'{name}.{target}'
            subprocess.run([args.dxc, *flags, '-Wno-ignored-attributes', *defines, '-T', profile, '-E', entry,
                            '-Fo', str(binary), str(source)], check=True)
            blob = binary.read_bytes()
            text += f'inline constexpr unsigned char {target}_{name}[]={{\n'
            text += ',\n'.join(','.join(str(b) for b in blob[i:i+32]) for i in range(0, len(blob), 32)) + '\n};\n'
    text += 'inline constexpr const char* vertex_entry="sdl_vertex_textured_main";\n'
    text += 'inline constexpr const char* fragment_entry="fragment_textured_main";\n'
text += '}\n'
output.parent.mkdir(parents=True, exist_ok=True)
output.write_text(text, encoding='utf-8', newline='\n')
